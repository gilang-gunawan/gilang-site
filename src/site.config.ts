export function getSocialLinks(): SocialLink[] {
  const links: SocialLink[] = [];
  for (const item of socialPlatforms) {
    const href = contact[item.key];
    if (href && href.trim() !== '') {
      links.push({
        key: item.key,
        label: item.label,
        href,
        icon: item.icon,
      });
    }
  }
  return links;
}

